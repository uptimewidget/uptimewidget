const DICTS: Record<Lang, Dict> = { en, de, es, fr, zh };

export let lang: Lang = "en";
export let t: Dict = en;

/** Loads the language chosen in the backend; reloads the window when it changes. */
export async function initI18n(): Promise<void> {
  const code = (await invoke<string>("get_language")) as Lang;
  lang = code in DICTS ? code : "en";
  t = DICTS[lang];
  document.documentElement.lang = lang;
  await listen("language-changed", () => location.reload());
}

export function errorMessage(code: unknown): string {
  return t.errors[String(code)] ?? t.errors.unexpected;
}
